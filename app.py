
from pathlib import Path

import pandas as pd
import streamlit as st

# ---------------- PAGE CONFIGURATION ----------------
st.set_page_config(
    page_title="Customer Lifetime Value Prediction",
    page_icon="📊",
    layout="wide",
)

BASE_DIR = Path(__file__).resolve().parent
OUTPUT_DIR = BASE_DIR / "clv_outputs"

st.title("Customer Lifetime Value Prediction")
st.markdown(
    "An interactive customer analytics dashboard using "
    "your completed MCA Data Analytics project."
)

# ---------------- LOAD PROJECT OUTPUTS ----------------
@st.cache_data
def load_csv(filename):
    path = OUTPUT_DIR / filename
    if path.exists():
        return pd.read_csv(path)
    return None


segments = load_csv("customer_clv_segments.csv")
models = load_csv("model_comparison.csv")
summary = load_csv("segment_summary.csv")
monthly = load_csv("monthly_revenue.csv")
retention = load_csv("retention_by_recency.csv")


# ---------------- MODEL COMPARISON ----------------
st.header("1. Model Performance")

if models is not None:
    st.dataframe(models, use_container_width=True, hide_index=True)

    if "MAE (GBP)" in models.columns:
        best = models.loc[models["MAE (GBP)"].idxmin()]
        st.success(
            f"Lowest MAE: {best['Model']} — "
            f"£{best['MAE (GBP)']:,.2f}"
        )
else:
    st.warning("model_comparison.csv was not found.")


# ---------------- CUSTOMER SUMMARY ----------------
st.header("2. Customer Overview")

if segments is not None:
    required = {"CLV_12m_GBP", "Segment"}

    if required.issubset(segments.columns):
        total_customers = len(segments)
        total_clv = segments["CLV_12m_GBP"].sum()
        avg_clv = segments["CLV_12m_GBP"].mean()

        c1, c2, c3 = st.columns(3)
        c1.metric("Customers scored", f"{total_customers:,}")
        c2.metric("Predicted 12-month value", f"£{total_clv:,.2f}")
        c3.metric("Average predicted CLV", f"£{avg_clv:,.2f}")

        st.caption(
            "These figures come from the predictions already "
            "generated by your notebook."
        )
    else:
        st.warning("The customer CSV has unexpected column names.")
else:
    st.warning("customer_clv_segments.csv was not found.")


# ---------------- CUSTOMER SEARCH ----------------
st.header("3. Search for a Customer")

if segments is not None and "CustomerID" in segments.columns:
    customer_id = st.text_input(
        "Enter an existing Customer ID",
        placeholder="For example, 17850",
    )

    if customer_id.strip():
        matches = segments[
            segments["CustomerID"].astype(str).str.strip()
            == customer_id.strip()
        ]

        if not matches.empty:
            customer = matches.iloc[0]

            st.subheader(f"Customer {customer_id}")

            a, b, c = st.columns(3)

            if "CLV_12m_GBP" in customer.index:
                a.metric(
                    "Predicted 12-month CLV",
                    f"£{customer['CLV_12m_GBP']:,.2f}",
                )

            if "Pred_value_90d_GBP" in customer.index:
                b.metric(
                    "Predicted 90-day value",
                    f"£{customer['Pred_value_90d_GBP']:,.2f}",
                )

            c.metric("Segment", str(customer["Segment"]))

            st.dataframe(
                matches,
                use_container_width=True,
                hide_index=True,
            )
        else:
            st.info(
                "No matching customer was found. "
                "Try an ID from the customer dataset."
            )
else:
    st.info("Customer search requires the customer segments CSV.")


# ---------------- SEGMENT ANALYSIS ----------------
st.header("4. Customer Segmentation")

if segments is not None and "Segment" in segments.columns:
    available_segments = sorted(
        segments["Segment"].dropna().unique().tolist()
    )

    chosen = st.selectbox(
        "Filter by customer segment",
        ["All segments"] + available_segments,
    )

    filtered = segments.copy()

    if chosen != "All segments":
        filtered = filtered[filtered["Segment"] == chosen]

    st.dataframe(filtered, use_container_width=True, hide_index=True)

    st.download_button(
        "Download filtered customer data",
        data=filtered.to_csv(index=False).encode("utf-8"),
        file_name="filtered_customer_clv.csv",
        mime="text/csv",
    )

    st.subheader("Customers by Segment")
    counts = (
        segments["Segment"]
        .value_counts()
        .rename_axis("Segment")
        .reset_index(name="Customers")
    )
    st.bar_chart(counts.set_index("Segment"))

if summary is not None:
    st.subheader("Segment Summary")
    st.dataframe(summary, use_container_width=True)


# ---------------- EXISTING PROJECT CHARTS ----------------
st.header("5. Project Visualizations")

chart_files = sorted(OUTPUT_DIR.glob("fig*.png"))

if chart_files:
    for start in range(0, len(chart_files), 2):
        columns = st.columns(2)

        for col, chart in zip(
            columns, chart_files[start:start + 2]
        ):
            with col:
                st.image(
                    str(chart),
                    caption=chart.stem.replace("_", " ").title(),
                    use_container_width=True,
                )
else:
    st.info(
        "No chart images found in clv_outputs. "
        "Run the notebook to generate them."
    )


# ---------------- OTHER OUTPUTS ----------------
with st.expander("Monthly Revenue Data"):
    if monthly is not None:
        st.dataframe(monthly, use_container_width=True)
    else:
        st.info("monthly_revenue.csv was not found.")

with st.expander("Retention by Recency"):
    if retention is not None:
        st.dataframe(retention, use_container_width=True)
    else:
        st.info("retention_by_recency.csv was not found.")


st.divider()
st.caption(
    "Customer Lifetime Value Prediction | "
    "MCA Data Analytics | Galgotias University"
)
